//! Execute a [`Plan`], streaming progress as [`Event`]s.
//!
//! Consecutive steps with the same privilege are written into a single bash
//! script, so a whole run needs at most one password prompt per root segment
//! (normally exactly one). Step boundaries are reported by marker lines the
//! script prints, which the runner strips from the output.

use std::{
    io::{BufRead, BufReader, Read, Write},
    path::{Path, PathBuf},
    process::Stdio,
    thread,
};

use crossbeam_channel::{Receiver, Sender, unbounded};

use crate::{
    Distro, Elevation,
    log::Logger,
    plan::{Plan, Step},
    shell,
};

const MARKER: &str = "\u{1e}NX ";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Event {
    StepStarted {
        index: usize,
    },
    Output {
        line: String,
    },
    StepFinished {
        index: usize,
        success: bool,
    },
    /// Always the last event.
    Finished {
        failed: Vec<usize>,
        log: Option<PathBuf>,
    },
}

#[derive(Debug, Clone)]
pub struct RunContext {
    pub scripts_dir: PathBuf,
    pub distro: Distro,
    pub elevation: Elevation,
}

/// Environment exported to every script.
pub fn script_env(scripts_dir: &Path, distro: &Distro) -> Vec<(&'static str, String)> {
    let user = std::env::var("SUDO_USER")
        .or_else(|_| std::env::var("USER"))
        .unwrap_or_default();
    let home = std::env::var("HOME").unwrap_or_default();
    vec![
        ("NX_SCRIPTS", scripts_dir.display().to_string()),
        ("NX_FAMILY", distro.family.to_string()),
        ("NX_DISTRO_ID", distro.id.clone()),
        (
            "NX_DISTRO_VERSION",
            distro.version_id.clone().unwrap_or_default(),
        ),
        ("NX_USER", user),
        ("NX_HOME", home),
    ]
}

pub fn spawn(plan: Plan, ctx: RunContext) -> Receiver<Event> {
    let (tx, rx) = unbounded();
    thread::spawn(move || run(&plan, &ctx, &tx));
    rx
}

/// Run synchronously. Returns indices of failed steps.
pub fn run(plan: &Plan, ctx: &RunContext, tx: &Sender<Event>) -> Vec<usize> {
    let mut log = Logger::create().ok();
    if let Some(l) = log.as_mut() {
        l.line(&format!(
            "distro: {} ({})",
            ctx.distro.name, ctx.distro.family
        ));
        l.line("plan:");
        for line in plan.render().lines() {
            l.line(line);
        }
        l.line("---");
    }
    let mut finished = vec![None::<bool>; plan.steps.len()];

    for (root, indices) in segments(&plan.steps) {
        let res = run_segment(plan, &indices, root, ctx, tx, &mut log, &mut finished);
        if let Err(e) = res {
            emit_line(tx, &mut log, format!("nxtoolkit: {e}"));
        }
        // Steps that never reported (auth cancelled, crash) count as failed.
        for &i in &indices {
            if finished[i].is_none() {
                finished[i] = Some(false);
                let _ = tx.send(Event::StepFinished {
                    index: i,
                    success: false,
                });
            }
        }
    }

    let failed: Vec<usize> = finished
        .iter()
        .enumerate()
        .filter(|(_, ok)| **ok != Some(true))
        .map(|(i, _)| i)
        .collect();
    if let Some(l) = log.as_mut() {
        l.line(&format!("--- done, {} failed", failed.len()));
    }
    let _ = tx.send(Event::Finished {
        failed: failed.clone(),
        log: log.map(|l| l.path),
    });
    failed
}

/// Group consecutive steps by privilege.
fn segments(steps: &[Step]) -> Vec<(bool, Vec<usize>)> {
    let mut out: Vec<(bool, Vec<usize>)> = Vec::new();
    for (i, s) in steps.iter().enumerate() {
        match out.last_mut() {
            Some((root, idx)) if *root == s.root => idx.push(i),
            _ => out.push((s.root, vec![i])),
        }
    }
    out
}

/// The bash script for one segment.
pub fn segment_script(plan: &Plan, indices: &[usize], ctx: &RunContext) -> String {
    let mut s = String::from("#!/usr/bin/env bash\n# generated by nxtoolkit\nexec 2>&1\n");
    for (k, v) in script_env(&ctx.scripts_dir, &ctx.distro) {
        s.push_str(&format!("export {k}={}\n", shell::quote(&v)));
    }
    s.push_str("export DEBIAN_FRONTEND=noninteractive\n");
    for &i in indices {
        let step = &plan.steps[i];
        s.push_str(&format!("\nprintf '\\036NX START {i}\\n'\n"));
        s.push_str(&format!("# {}\n", step.label.replace('\n', " ")));
        s.push_str("(\nset -euo pipefail\n");
        s.push_str(&step.command);
        s.push_str("\n) </dev/null\n");
        s.push_str(&format!("printf '\\036NX END {i} %d\\n' \"$?\"\n"));
    }
    s
}

fn run_segment(
    plan: &Plan,
    indices: &[usize],
    root: bool,
    ctx: &RunContext,
    tx: &Sender<Event>,
    log: &mut Option<Logger>,
    finished: &mut [Option<bool>],
) -> std::io::Result<()> {
    let mut file = tempfile::Builder::new()
        .prefix("nxtoolkit-run-")
        .suffix(".sh")
        .tempfile()?;
    file.write_all(segment_script(plan, indices, ctx).as_bytes())?;
    file.flush()?;

    let mut cmd = if root {
        ctx.elevation.command(file.path())
    } else {
        let mut c = std::process::Command::new("bash");
        c.arg(file.path()).stdin(Stdio::null());
        c
    };
    let mut child = cmd.stdout(Stdio::piped()).stderr(Stdio::piped()).spawn()?;

    let (ltx, lrx) = unbounded::<String>();
    let readers = [
        pump(
            child
                .stdout
                .take()
                .map(|r| Box::new(r) as Box<dyn Read + Send>),
            ltx.clone(),
        ),
        pump(
            child
                .stderr
                .take()
                .map(|r| Box::new(r) as Box<dyn Read + Send>),
            ltx,
        ),
    ];

    for line in lrx {
        if let Some(rest) = line.strip_prefix(MARKER) {
            let mut parts = rest.split_whitespace();
            match (
                parts.next(),
                parts.next().and_then(|n| n.parse::<usize>().ok()),
            ) {
                (Some("START"), Some(i)) if indices.contains(&i) => {
                    if let Some(l) = log.as_mut() {
                        l.line(&format!(">>> [{}] {}", i + 1, plan.steps[i].label));
                    }
                    let _ = tx.send(Event::StepStarted { index: i });
                }
                (Some("END"), Some(i)) if indices.contains(&i) => {
                    let code: i32 = parts.next().and_then(|c| c.parse().ok()).unwrap_or(1);
                    let success = code == 0;
                    finished[i] = Some(success);
                    if let Some(l) = log.as_mut() {
                        l.line(&format!("<<< [{}] exit {code}", i + 1));
                    }
                    let _ = tx.send(Event::StepFinished { index: i, success });
                }
                _ => emit_line(tx, log, line),
            }
        } else {
            emit_line(tx, log, line);
        }
    }
    for r in readers.into_iter().flatten() {
        let _ = r.join();
    }
    let status = child.wait()?;
    if !status.success() && indices.iter().all(|&i| finished[i].is_none()) {
        let hint = match (root, ctx.elevation) {
            (true, Elevation::Pkexec) => " (authentication cancelled or failed?)",
            (true, Elevation::Sudo) => " (sudo credentials expired or denied?)",
            _ => "",
        };
        emit_line(
            tx,
            log,
            format!("nxtoolkit: script exited with {status}{hint}"),
        );
    }
    Ok(())
}

fn pump(src: Option<Box<dyn Read + Send>>, tx: Sender<String>) -> Option<thread::JoinHandle<()>> {
    let src = src?;
    Some(thread::spawn(move || {
        let reader = BufReader::new(src);
        for chunk in reader.split(b'\n') {
            let Ok(bytes) = chunk else { break };
            let text = String::from_utf8_lossy(&bytes);
            // Progress bars redraw with \r; keep only the final state.
            let line = text
                .rsplit('\r')
                .find(|s| !s.is_empty())
                .unwrap_or("")
                .to_string();
            if tx.send(line).is_err() {
                break;
            }
        }
    }))
}

fn emit_line(tx: &Sender<Event>, log: &mut Option<Logger>, line: String) {
    if let Some(l) = log.as_mut() {
        l.line(&line);
    }
    let _ = tx.send(Event::Output { line });
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Family;

    fn ctx() -> RunContext {
        RunContext {
            scripts_dir: "/nonexistent".into(),
            distro: Distro::synthetic(Family::Fedora),
            elevation: Elevation::AlreadyRoot,
        }
    }

    fn step(label: &str, cmd: &str) -> Step {
        Step {
            label: label.into(),
            root: false,
            command: cmd.into(),
        }
    }

    #[test]
    fn segments_group_by_privilege() {
        let mut steps = vec![step("a", "true"), step("b", "true"), step("c", "true")];
        steps[2].root = true;
        assert_eq!(segments(&steps), vec![(false, vec![0, 1]), (true, vec![2])]);
    }

    #[test]
    fn runs_user_steps_and_reports() {
        let plan = Plan {
            steps: vec![
                step("ok", "echo hello; echo err >&2"),
                step("fail", "false; echo unreachable"),
                step("env", "echo \"family=$NX_FAMILY\""),
            ],
            ..Default::default()
        };
        let (tx, rx) = unbounded();
        let failed = run(&plan, &ctx(), &tx);
        assert_eq!(failed, vec![1]);
        let events: Vec<Event> = rx.try_iter().collect();
        let lines: Vec<&str> = events
            .iter()
            .filter_map(|e| match e {
                Event::Output { line } => Some(line.as_str()),
                _ => None,
            })
            .collect();
        assert!(lines.contains(&"hello"));
        assert!(lines.contains(&"err"));
        assert!(lines.contains(&"family=fedora"));
        assert!(!lines.contains(&"unreachable"));
        assert!(events.contains(&Event::StepFinished {
            index: 0,
            success: true
        }));
        assert!(events.contains(&Event::StepFinished {
            index: 1,
            success: false
        }));
        assert!(matches!(events.last(), Some(Event::Finished { .. })));
    }
}
